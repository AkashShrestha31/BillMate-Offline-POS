  static Iterable<CountryTaxProfile> get allProfiles => _profiles.values;

  static CountryTaxProfile? maybeOf(String country) {
    final key = _aliases[country] ?? country;
    return _profiles[key];
  }

  static CountryTaxProfile of(String country) {
    final profile = maybeOf(country);
    if (profile != null) return profile;
    final currency =
        SetupRegionOptions.currencyCodeForCountry(country) ?? 'NPR';
    return CountryTaxProfile(
      country: country,
      currencies: [currency],
      entityTinLabels: const ['TIN'],
      vatRateOptions: const [0.0],
    );
  }

  /// Every distinct VAT/GST / sales-tax rate from the reference document.
  static List<double> get allVatRates {
    final rates = <double>{0.0};
    for (final profile in _profiles.values) {
      rates.addAll(profile.vatRateOptions);
    }
    final sorted = rates.toList()..sort();
    return sorted;
  }

  /// Currencies for [country] first, then every other catalog currency.
  static List<String> currencyChoicesFor(String country) {
    final preferred = of(country).currencies;
    final all = <String>{
      ...preferred,
      ...SetupRegionOptions.countries().map((c) => c.currencyCode).toSet(),
    };
    final rest = all.where((c) => !preferred.contains(c)).toList()..sort();
    return [...preferred, ...rest];
  }
