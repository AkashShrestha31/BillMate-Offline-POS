/// Country tax defaults from Country_TaxID_Currency_TaxRates_FiscalYear
/// (September 2026). VAT/GST, corporate, and personal (PIT) are stored
/// separately. Range values keep the first (lower) rate as the default.
class CountryTaxProfile {
  const CountryTaxProfile({
    required this.country,
    required this.currencies,
    required this.entityTinLabels,
    required this.vatRateOptions,
    this.individualTinLabels = const [],
    this.vatTinLabels = const [],
    this.corporateRateOptions = const [],
    this.pitRateOptions = const [],
  });

  final String country;
  final List<String> currencies;
  final List<String> entityTinLabels;
  final List<String> vatTinLabels;
  final List<double> vatRateOptions;
  final List<String> individualTinLabels;
  final List<double> corporateRateOptions;
  final List<double> pitRateOptions;

  String get primaryCurrency => currencies.first;
  String? get primaryTinLabel =>
      entityTinLabels.isEmpty ? null : entityTinLabels.first;
  double get primaryVatRate =>
      vatRateOptions.isEmpty ? 0 : vatRateOptions.first;
  bool get needsCurrencyChoice => currencies.length > 1;
  bool get needsTinChoice =>
      entityTinLabels.length > 1 || vatTinLabels.isNotEmpty;
  bool get needsVatChoice => vatRateOptions.length > 1;
}

CountryTaxProfile _t(
  String country, {
  required List<String> currencies,
  List<String> entity = const [],
  List<String> individual = const [],
  List<String> vatTin = const [],
  required List<double> vat,
  required List<double> corp,
  required List<double> pit,
}) {
  return CountryTaxProfile(
    country: country,
    currencies: currencies,
    entityTinLabels: entity,
    individualTinLabels: individual,
    vatTinLabels: vatTin,
    vatRateOptions: vat,
    corporateRateOptions: corp,
    pitRateOptions: pit,
  );
}

